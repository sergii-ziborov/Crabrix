use std::{fs, io, path::Path};
fn escape_html(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&#39;"),
            other => escaped.push(other),
        }
    }
    escaped
}
fn page(title: &str) -> String {
    let title = escape_html(title);
    format!(r#"<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title><link rel="stylesheet" href="styles.css">
<script src="app.js" defer></script></head>
<body><main><h1>{title}</h1><p>Generated by Rust. Interactive in the browser.</p>
<button id="counter" type="button">Clicks: 0</button>
<p id="status" role="status">Ready.</p></main></body></html>"#)
}
fn main() -> io::Result<()> {
    let root = Path::new(if cfg!(target_os = "wasi") { "/sandbox" } else { "web-output" });
    fs::create_dir_all(root)?;
    fs::write(root.join("index.html"), page("Rust & local web pages"))?;
    fs::write(root.join("styles.css"), r#"
:root { font-family: system-ui, sans-serif; color: #eef4f3; background: #101b26; }
main { max-width: 38rem; margin: 3rem auto; padding: 1.5rem; line-height: 1.6; }
button { font: inherit; background: #7de0c3; border: 0; border-radius: 2rem; padding: .8rem 1.4rem; }
button:focus-visible { outline: 3px solid #ffc45d; outline-offset: 4px; }
"#)?;
    fs::write(root.join("app.js"), r#"
const button = document.querySelector('#counter');
let clicks = 0;
button.addEventListener('click', () => {
    button.textContent = `Clicks: ${++clicks}`;
    document.querySelector('#status').textContent = 'This JavaScript runs locally.';
});
"#)?;
    println!("Generated index.html, styles.css and app.js");
    Ok(())
}
#[cfg(test)]
mod tests {
    #[test]
    fn text_is_escaped_without_becoming_markup() {
        assert_eq!(super::escape_html("A & <B> \"x\" 'y'"), "A &amp; &lt;B&gt; &quot;x&quot; &#39;y&#39;");
        assert!(super::page("<script>").contains("<h1>&lt;script&gt;</h1>"));
    }
}
