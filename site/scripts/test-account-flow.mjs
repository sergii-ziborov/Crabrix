// End-to-end account/access test. Uses an isolated account and deletes it afterwards.
// Run: PLAYWRIGHT_MODULE=/path/to/playwright/index.mjs node scripts/test-account-flow.mjs
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdirSync, readFileSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.QA_SITE_ORIGIN || 'http://localhost:3014';
const username = `qa_${randomBytes(6).toString('hex')}`;
const password = randomBytes(24).toString('base64url');
const newPassword = randomBytes(24).toString('base64url');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
const page = await context.newPage();
const snapshot = JSON.parse(readFileSync(new URL('../content/courses.json', import.meta.url)));
const lesson = snapshot.courses.find(c => c.id === 'basics').units.flatMap(u => u.lessons).find(l => l.id === 'variables');
const route = '/learn/basics/variables/';
const hidden = lesson.writing.question.replaceAll('`', '');
const rawHidden = lesson.writing.explanation.split('\n\n').at(-1).slice(0, 100);
const guest = await context.request.get(base + route);
assert.equal(guest.status(), 200);
assert.ok(!(await guest.text()).includes(rawHidden));
const flight = await context.request.get(base + route, { headers: { RSC: '1' } });
assert.ok(!(await flight.text()).includes(rawHidden), 'full text leaked through RSC');
assert.equal((await context.request.get(base + '/learn-media/basics/variables.png')).status(), 401);
assert.equal((await context.request.get(base + '/content/courses.json')).status(), 404);
await page.goto(base + route);
assert.ok(!(await page.locator('body').innerText()).includes(hidden));
assert.equal(await page.locator('.lesson-access').count(), 1);
await page.goto(base + '/register/?next=' + encodeURIComponent(route));
mkdirSync('../docs/screenshots', { recursive: true });
if (process.env.QA_CAPTURE === '1') {
  await page.screenshot({ path: '../docs/screenshots/site-registration-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '../docs/screenshots/site-registration-mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'mobile page overflow');
  await page.setViewportSize({ width: 1440, height: 1100 });
}
await page.locator('input[name=username]').fill(username);
await page.locator('input[name=password]').fill(password);
await page.locator('input[name=confirm]').fill(password);
await page.locator('input[name=terms]').check();
await page.getByRole('button', { name: 'Create free account', exact: true }).click();
await page.locator('.recovery-code').waitFor();
const recoveryCode = await page.locator('.recovery-code').innerText();
assert.equal(recoveryCode.replaceAll('-', '').length, 40);
const cookie = (await context.cookies()).find(c => /crabrix_session/.test(c.name));
assert.ok(cookie.httpOnly);
assert.equal(cookie.sameSite, 'Lax');
assert.equal(cookie.secure, base.startsWith('https:'));
await page.getByRole('checkbox', { name: 'I have saved my username and recovery code.' }).check();
await page.getByRole('link', { name: 'Continue learning' }).click();
await page.getByRole('heading', { name: 'Check your understanding' }).waitFor();
assert.ok((await page.locator('body').innerText()).includes(hidden));
assert.equal((await context.request.get(base + '/learn-media/basics/variables.png')).status(), 200);
const fullResponse = await context.request.get(base + route);
assert.ok(/no-store|private/.test(fullResponse.headers()['cache-control']));
await page.goto(base + '/account/');
const exported = await context.request.get(base + '/account/export/');
assert.equal((await exported.json()).username, username);
await page.getByRole('button', { name: 'Sign out', exact: true }).click();
await page.waitForURL(base + '/learn/');
assert.equal((await context.request.get(base + '/learn-media/basics/variables.png')).status(), 401);
await page.goto(base + '/login/?next=' + encodeURIComponent(route));
await page.locator('input[name=username]').fill(username);
await page.locator('input[name=password]').fill(password);
await page.getByRole('button', { name: 'Sign in', exact: true }).click();
await page.getByRole('heading', { name: 'Check your understanding' }).waitFor();
await page.goto(base + '/account/');
await page.getByRole('button', { name: 'Sign out', exact: true }).click();
await page.waitForURL(base + '/learn/');
await page.goto(base + '/recover/?next=' + encodeURIComponent(route));
await page.locator('input[name=username]').fill(username);
await page.locator('input[name=recoveryCode]').fill(recoveryCode);
await page.locator('input[name=password]').fill(newPassword);
await page.locator('input[name=confirm]').fill(newPassword);
await page.getByRole('button', { name: 'Recover account', exact: true }).click();
await page.locator('.recovery-code').waitFor();
assert.notEqual(await page.locator('.recovery-code').innerText(), recoveryCode);
await page.goto(base + '/account/');
await page.locator('input[name=password]').last().fill(newPassword);
await page.locator('input[name=confirmation]').fill('DELETE');
await page.getByRole('button', { name: 'Delete my account', exact: true }).click();
await page.waitForURL(/deleted=1/);
assert.equal((await context.request.get(base + '/account/export/')).status(), 401);
const finalResponse = await context.request.get(base + route);
assert.ok((await finalResponse.text()).includes('Lesson preview'));
await browser.close();
console.log('PASS: preview/RSC withholding, private media, registration, session flags, full lesson, export, logout, login, recovery, deletion');
