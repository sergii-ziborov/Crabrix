            fn noise(x: u32, y: u32) -> u32 {
                let mut value = x.wrapping_mul(374_761_393)
                    ^ y.wrapping_mul(668_265_263);
                value = (value ^ (value >> 13))
                    .wrapping_mul(1_274_126_177);
