import Foundation

/// Projects that exercise real Rust algorithms and render their bounded result
/// in the native Output canvas. The source stays ordinary std-only Rust and is
/// fully editable; `README.md` turns each entry into a guided challenge.
enum RustVisualShowcaseCatalog {
    private static func project(
        id: String,
        title: String,
        detail: String,
        difficulty: RustShowcaseDifficulty,
        concepts: [String],
        challenge: String,
        source: String
    ) -> RustShowcaseProject {
        RustShowcaseProject(
            id: id,
            title: title,
            detail: detail,
            systemImage: "paintpalette.fill",
            category: .graphics,
            difficulty: difficulty,
            concepts: concepts,
            project: CrabrixProject(
                name: id,
                files: [
                    "Cargo.toml": RustShowcaseCatalog.manifest(
                        name: id
                    ),
                    "README.md": """
                    # \(title)

                    Run the project and open **Output** to see a native Rust Canvas.

                    ## Concepts
                    \(concepts.map { "- `\($0)`" }.joined(separator: "\n"))

                    ## Challenge
                    \(challenge)

                    ## Proof
                    The result is generated by the bundled compiler and rendered
                    only after Crabrix validates every dimension, palette color,
                    and pixel index.
                    """,
                    "src/main.rs": source,
                ],
                entryFile: "src/main.rs",
                provenance: nil,
                projectDescription: detail,
                tags: concepts,
                folder: "Visual Gallery",
                kind: .visual
            )
        )
    }

